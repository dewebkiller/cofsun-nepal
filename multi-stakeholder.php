                    <p>Nepal is struggling with political transition over the last seven years. After the death of constituent assembly (CA) in May 2012 without promulgation of new constitution for the country, Nepal is running without accountable government. It is irony that Ministry of Forest and Soil Conversation (MoFSC) is likely to develop policies related to Forestry Sector strategy, National Conservation Strategy, REDD Strategy and Nepal Biodiversity Strategy for which concerns of multi-stakeholders and general public require to be reflected properly. By considering such an existing scenario, this program is designed in such a way that several forums (district and national levels) for multi-stakeholders dialogues are created in the areas of Green Job, Governance, tackling climate change and Community property rights. In this expected forums, participations of key political actors, representatives of civil society, grass roots stakeholders and concerned bureaucrats are ensured so that different concerns and commitments are expressed and ultimately those concerns and commitments will contribute to policy development. On the other side recent political development indicates that there will be another fresh election for CA. That event will be a suitable opportunity for policy advocates for advocating major political parties to get incorporated the concerns of multi-stakeholders in their election manifestoes for community rights. Advocacy and persuasions to major political parties can be done through Green Reporters Club and media campaign.</p>
                    <p><strong>Objectives</strong></p>
                    <p>
                        To conduct multi-stakeholder dialogue on NRM related issues and thematic consultation at district level (at least 25 districts).
                        To explore issues related to NRM through the multi stakeholder dialogue and to create environment to express commitment for community right at national level.
                        To set up Green Reporters Club and organize the NRM issue based interaction and broadcasting/publishing national TV and print media at national level to pressurize to entertain community right.
