                    <h1 class="mb-3">Consultations for Developing Nepal’s ER-PD</h1>

                    <p>Nepal’s Emission Reduction Program Idea Notes (ER-PIN) for the 12 districts of the Terai Arc Landscape (TAL) has already been approved by the Carbon Fund of the FCPF and is into the Carbon Fund pipeline. The Government of Nepal is now positioned to prepare the full Emission Reduction Program Document (ER-PD) detailing the REDD+ program design. The ER-PD needs to be developed in a transparent, consultative and participatory manner that engages major constituencies and stakeholders. WWF, as the selected organization by the World Bank to provide technical assistance to the Government of Nepal, REDD Implementation Centre (REDD IC) to assist to develop the ER-PD – has planned 43 consultations across national, regional and district levels.
                    </p>
                    <p>In line with guidance from the REDD IC and suggestions received during the Inception Workshop, WWF has initiated three national, four regional and 36 district level consultations. In this consultation context, COFSUN, Nepal has conducted six district level consultations out of 36 district level consultation in collaboration with different IPOs and CSOs. COFSUN, Nepal has conducted consultations in Rupandehi, Dang, Banke, Bardia, Kailali and Kanchapur Districts and provided suggestions and feedback on ER-PD.</p>
